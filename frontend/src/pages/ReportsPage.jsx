import { useEffect, useState } from 'react'
import { Download, FileText, AlertTriangle } from 'lucide-react'
import PageHeader from '../components/common/PageHeader'
import Card from '../components/common/Card'
import EmptyState from '../components/common/EmptyState'
import ErrorState from '../components/common/ErrorState'
import Spinner from '../components/common/Spinner'
import Button from '../components/common/Button'
import apiClient from '../services/apiClient'
import { getToken } from '../services/authStorage'

export default function ReportsPage() {
  const [reports, setReports] = useState(null)
  const [error, setError] = useState(null)

  useEffect(() => {
    let cancelled = false
    apiClient
      .get('/reports')
      .then(({ data }) => {
        if (!cancelled) setReports(data.reports)
      })
      .catch(() => {
        if (!cancelled) setError('Could not load reports. Is the Node API running?')
      })
    return () => {
      cancelled = true
    }
  }, [])

  return (
    <div className="space-y-6">
      <PageHeader title="Reports" subtitle="Download reports generated by your AI modules." />

      {error && <ErrorState title="Could not load reports." description="Is the Node API running?" />}
      {!reports && !error && <Spinner label="Loading reports…" />}

      {reports && reports.length === 0 && (
        <EmptyState
          icon={FileText}
          title="No reports yet."
          description="Export a report from any completed job to see it here, or browse Processing History."
        />
      )}

      {reports && reports.length > 0 && (
        <Card padding="none" className="overflow-x-auto">
          <table className="w-full text-left text-sm">
            <thead className="border-b border-slate-200/80 bg-slate-50/60 text-xs uppercase tracking-wide text-slate-400 dark:border-white/10 dark:bg-white/[0.03] dark:text-slate-500">
              <tr>
                <th className="px-4 py-3 font-semibold">Module</th>
                <th className="px-4 py-3 font-semibold">Type</th>
                <th className="px-4 py-3 font-semibold">Job ID</th>
                <th className="px-4 py-3 font-semibold">Created</th>
                <th className="px-4 py-3 font-semibold" />
              </tr>
            </thead>
            <tbody className="divide-y divide-slate-100 dark:divide-white/5">
              {reports.map((report) => (
                <tr key={report._id} className="transition-colors hover:bg-slate-50/80 dark:hover:bg-white/[0.03]">
                  <td className="px-4 py-3 text-slate-700 dark:text-slate-300">{report.moduleId}</td>
                  <td className="px-4 py-3 uppercase text-slate-700 dark:text-slate-300">{report.type}</td>
                  <td className="px-4 py-3 font-mono text-xs text-slate-500 dark:text-slate-400">{report.jobId}</td>
                  <td className="px-4 py-3 text-slate-500 dark:text-slate-400">{new Date(report.createdAt).toLocaleString()}</td>
                  <td className="px-4 py-3 text-right">
                    <Button
                      as="a"
                      href={`${apiClient.defaults.baseURL}/reports/${report._id}/download?token=${getToken()}`}
                      variant="ghost"
                      size="sm"
                      className="px-0 hover:bg-transparent hover:underline"
                    >
                      <Download size={14} />
                      Download
                    </Button>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </Card>
      )}
    </div>
  )
}
